const dict = { en, lt };

interface I18n {
  lang: Lang;
  toggle: () => void;
  t: (k: Key, vars?: Record<string, string | number>) => string;
}
const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() =>
    localStorage.getItem("eneba.lang") === "lt" ? "lt" : "en",
  );
  useEffect(() => {
    document.documentElement.lang = lang;
    localStorage.setItem("eneba.lang", lang);
  }, [lang]);
  const toggle = useCallback(() => setLang((l) => (l === "en" ? "lt" : "en")), []);
  const t = useCallback(
    (k: Key, vars?: Record<string, string | number>) => {
      let s = dict[lang][k];
      if (vars) for (const [v, val] of Object.entries(vars)) s = s.replace(`{${v}}`, String(val));
      return s;
    },
    [lang],
  );
  return <Ctx.Provider value={{ lang, toggle, t }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n must be used inside I18nProvider");
  return v;
}
